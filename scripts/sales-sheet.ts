/**
 * Writes docs/sales/PACKAGE_GUIDE.md for the sales team from the same config the product runs on
 * (src/lib/workspace/packages.ts + industries.ts), so the guide cannot promise what the system does not do.
 * Run: npm run sales:sheet
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { INDUSTRIES, INDUSTRY_IDS } from "../src/lib/workspace/industries";
import { ADDONS, CAPABILITY_STATUS, PACKAGES, PACKAGE_IDS, type Package } from "../src/lib/workspace/packages";

const usd = (n: number) => `$${n.toLocaleString("en-US")}`;
const lines: string[] = [];
const add = (...l: string[]) => lines.push(...l);

add("# Package guide for sales", "", "_Generated by `npm run sales:sheet` from the product's own config. Do not edit by hand._", "");

add("## Packages at a glance", "", "| | Starter | Growth | Advanced |", "|---|---|---|---|");
const row = (label: string, f: (p: Package) => string) => add(`| ${label} | ${PACKAGE_IDS.map((id) => f(PACKAGES[id])).join(" | ")} |`);
row("One-time setup", (p) => `from ${usd(p.setupUsd)}${p.id === "advanced" ? "+" : ""}`);
row("Monthly support", (p) => `from ${usd(p.supportUsd)}`);
row("Ready in", (p) => p.readyIn);
row("Enquiry channels", (p) => (p.channels === null ? "As agreed" : String(p.channels)));
row("Team members", (p) => (p.seats === null ? "As agreed" : `Up to ${p.seats}`));
row("Training", (p) => p.training);
row("Help after launch", (p) => `${p.helpDays} days`);
row("Revisions", (p) => p.revisions);
add(
  "",
  "Not included: hosting, databases and message fees (paid to the provider), third-party subscriptions, ongoing support (separate monthly plan), work outside the written scope.",
  "",
);

for (const id of PACKAGE_IDS) {
  const p = PACKAGES[id];
  add(`## ${p.name}: ${p.tagline}`, "", ...p.includes.map((i) => `- ${i}`), "", ...(p.notes ?? []).map((n) => `> ${n}`), ...(p.notes ? [""] : []));
}

const crm = ADDONS.starterCrm;
add(`## Add-on: ${crm.name}`, "", crm.summary, "", `Price: ${crm.priceUsd === null ? "quoted separately" : usd(crm.priceUsd)}. Not included in any package price.`, "");

add("## Internal: what is actually built today", "", "Do not promise `planned` or `partial` items as live without checking with the developer.", "");
add("| Feature | Status | Note |", "|---|---|---|");
for (const c of Object.values(CAPABILITY_STATUS)) add(`| ${c.label} | ${c.status} | ${c.note ?? ""} |`);
add("");

add("## By business type", "");
for (const group of ["General", "Sales", "Healthcare", "Education"] as const) {
  for (const id of INDUSTRY_IDS) {
    const i = INDUSTRIES[id];
    if (i.group !== group) continue;
    add(
      `### ${i.name} (${i.group}): starts with ${PACKAGES[i.startsWith].name}${i.proven ? "" : ", pack drafted and not yet proven with a client"}`,
      "",
      `- **An enquiry is:** ${i.enquiry}`,
      `- **Pipeline:** ${i.stages.join(" → ")}`,
      `- **We ask:** ${i.intake.join("; ")}`,
      `- **Specific to this business:** ${i.extra}`,
      ...(i.compliance ? [`- **Care needed:** ${i.compliance}`] : []),
      "",
      "| Package | What this business gets |",
      "|---|---|",
      "| Starter | Every enquiry captured, answered instantly and tagged hot/warm/cold, using the questions and pipeline above |",
      `| Growth | Starter, plus automatic follow-up, AI ranking of who to call first and reports; ${i.extra} |`,
      "| Advanced | Growth, plus a build scoped on the audit call for how this business runs (approvals, multiple teams, AI agents) |",
      "",
    );
  }
}
add("### Something else", "", "Built around you. Book the audit call; the written scope usually lands on Advanced.", "");

mkdirSync("docs/sales", { recursive: true });
writeFileSync("docs/sales/PACKAGE_GUIDE.md", lines.join("\n"), "utf8");
console.log(`Wrote docs/sales/PACKAGE_GUIDE.md (${lines.length} lines)`);
